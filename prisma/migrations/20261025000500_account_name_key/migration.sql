-- Account names: canonical (trimmed, NFC) display names and a persisted,
-- owner-scoped comparison key, `name_key` = NFC(toLowerCase(name)), computed
-- by the application (src/domain/finance/account-name.ts). Replaces the
-- (owner_id, lower(name)) index, whose meaning depended on the database's
-- collation provider. See docs/adr/0007-account-name-normalization.md.
--
-- Atomicity: `prisma migrate deploy` sends this whole file to PostgreSQL as
-- one simple-protocol query, which PostgreSQL runs as a single implicit
-- transaction. Any error (including the refusals in step 2) therefore rolls
-- back every statement here: no column, no index change, no rewritten name.
-- Prisma then records the migration as failed. Recovery is in
-- docs/runbooks/hosted-setup.md ("Account-name key migration"). This file
-- must not contain BEGIN/COMMIT or anything that cannot run in a transaction.
--
-- Accounts are never renamed or deleted to resolve a conflict. The only
-- intended change to existing names is NFC normalisation. The backfill
-- (step 5) updates every row with the guard trigger enabled, so every
-- account's updated_at moves to the migration time; no other column changes.
--
-- Deployment: no account may be written between this migration and the new
-- application code going live (docs/runbooks/hosted-setup.md). The old code
-- does not write name_key, so its inserts fail and its renames would leave a
-- stale key.

-- 0. Preconditions, before anything else runs.
--    lock_timeout: steps 3-6 need ACCESS EXCLUSIVE on financial_accounts.
--    Fail (rolling everything back) rather than wait indefinitely behind
--    another transaction while queueing every other query on the table.
--    SET LOCAL ends with this migration's transaction (see Atomicity) and
--    leaves the session's setting as it was.
SET LOCAL lock_timeout = '5s';

--    PostgreSQL 17 for unicode_assigned() (step 2); checked first so older
--    servers get this message rather than an unknown-function error.
DO $$
BEGIN
  IF current_setting('server_version_num')::integer < 170000 THEN
    RAISE EXCEPTION 'finora: the account-name key migration needs PostgreSQL 17 or later (found %)', current_setting('server_version')
      USING HINT = 'Upgrade PostgreSQL, then re-run migrations. Nothing was changed.';
  END IF;
END
$$;

