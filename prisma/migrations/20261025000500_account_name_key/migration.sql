-- 2. Refuse to proceed (changing nothing) unless every existing row can be
--    converted exactly as the application would and the result is unique.
--    `npm run db:account-names -- conflicts` lists the affected account ids
--    (never names) from the application's own code.
DO $$
DECLARE
  unsupported integer;
  untrimmed integer;
  too_long integer;
  conflicts integer;
BEGIN
  IF current_setting('server_encoding') <> 'UTF8' THEN
    RAISE EXCEPTION 'finora: account-name keys need a UTF8 database (found %)', current_setting('server_encoding');
  END IF;

  -- normalize() uses this server's Unicode tables. NFC agrees with the
  -- application's for characters both versions have assigned (Unicode
  -- normalisation stability), so refuse names with any character unassigned
  -- here.
  SELECT count(*) INTO unsupported FROM "finora"."financial_accounts" WHERE NOT unicode_assigned("name");
  IF unsupported > 0 THEN
    RAISE EXCEPTION 'finora: % account name(s) contain characters unassigned in this server''s Unicode %; they cannot be normalised exactly as the application does', unsupported, unicode_version()
      USING HINT = 'Rename those accounts, or upgrade PostgreSQL, then re-run migrations. List them with: npm run db:account-names -- conflicts';
  END IF;

  -- The application trims names; trimming here would change names silently.
  SELECT count(*) INTO untrimmed FROM "finora"."financial_accounts" WHERE NOT pg_temp.finora_account_name_is_trimmed("name");
  IF untrimmed > 0 THEN
    RAISE EXCEPTION 'finora: % account name(s) start or end with whitespace the application would trim', untrimmed
      USING HINT = 'Rename those accounts, then re-run migrations. List them with: npm run db:account-names -- conflicts';
  END IF;

  SELECT count(*) INTO too_long FROM "finora"."financial_accounts" WHERE char_length(normalize("name", NFC)) > 60;
  IF too_long > 0 THEN
    RAISE EXCEPTION 'finora: % account name(s) would exceed 60 characters after NFC normalisation', too_long
      USING HINT = 'Rename those accounts, then re-run migrations. List them with: npm run db:account-names -- conflicts';
  END IF;

  SELECT count(*) INTO conflicts
    FROM (
      SELECT 1 FROM "finora"."financial_accounts"
       GROUP BY "owner_id", pg_temp.finora_account_name_key("name") COLLATE "C"
      HAVING count(*) > 1
    ) AS duplicate_groups;
  IF conflicts > 0 THEN
    RAISE EXCEPTION 'finora: % group(s) of account names of one owner would share a comparison key', conflicts
      USING HINT = 'Rename accounts so each owner''s names differ by more than letter case or Unicode form, then re-run migrations. List them with: npm run db:account-names -- conflicts';
  END IF;
END
$$;

